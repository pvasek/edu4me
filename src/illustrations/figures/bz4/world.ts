/** Crop: longitudes −170…180, latitudes 80 N … 56 S. */
export const LON0 = -170;
export const LON1 = 180;
export const LAT0 = 80;
export const LAT1 = -56;

/** Projection into a box (x, y, w); returns the box height too. */
export function projector(x: number, y: number, w: number) {
  const k = w / (LON1 - LON0);
  const h = (LAT0 - LAT1) * k;
  const p = (lon: number, lat: number): [number, number] => [
    x + (lon - LON0) * k,
    y + (LAT0 - lat) * k,
  ];
  const ring = (pts: LL[]) =>
    "M" +
    pts
      .map(([lo, la]) => {
        const [px, py] = p(lo, la);
        return `${px.toFixed(1)} ${py.toFixed(1)}`;
      })
      .join(" L") +
    "Z";
  const land = Object.values(LAND).map(ring).join(" ");
  return { p, ring, land, h, k };
}
