/**
 * Engraving-style line icons, 24×24 grid, drawn with `currentColor`.
 *
 * Each icon is a list of shapes rendered by `ChemIconView` (ChemIcon.tsx):
 *  - a plain string is a stroked path (main stroke, 1.6);
 *  - objects add circles/ellipses, thin detail strokes, dashes, transforms
 *    and small accent fills (`soft` = currentColor at low opacity,
 *    `hatch` = engraved diagonal hatch, `solid` = full ink for tiny dots).
 * Fills are listed before the outlines that sit on top of them.
 */
