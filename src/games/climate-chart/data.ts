/**
 * Klimatogram – curated climate normals of real stations (monthly mean temperature °C,
 * monthly precipitation mm, January first). Every set is the 1991–2020 normal from the
 * station's climate table on English Wikipedia (`ref`; the tables cite the national
 * weather services, WMO and NOAA), checked in October 2026: the 12 values were read
 * one by one and their sum / mean compared with the table's yearly value.
 * Darwin: the table has no daily mean, so it is the mean of the daily maximum and minimum.
 *
 * `region` and `biome` are geography facts about the place (not computed); every
 * answer about the climate itself (warmest month, range, dry months, Köppen type …)
 * is computed from the numbers in logic.ts. Never type a number in by hand.
 */

export interface Station {
  id: string
  /** Czech name (exonym), with the station when it matters */
  name: string
  country: string
  /** degrees, north / east positive (only the hemisphere and a rough latitude are used) */
  lat: number
  lon: number
  /** station altitude, m n. m. (only where the table gives it) */
  altitude?: number
  /** region of the world as Czech textbooks name it */
  region: string
  /** krajinný pás (biome) of the place, where it is clear-cut */
  biome?: Biome
  temp: number[]
  precip: number[]
  /** normal period (shown under the chart) */
  source: string
  /** where the numbers were taken from */
  ref: string
}

